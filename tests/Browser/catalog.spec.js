import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { readFileSync } from 'node:fs';
test.describe.configure({retries:0});

test('real category navigation, subcategories and localization', async ({page},testInfo) => {
    await page.goto('/ro');
    expect(await page.locator('.home-categories .category-card').count()).toBeGreaterThanOrEqual(9);
    await page.screenshot({path:testInfo.outputPath('home-with-categories.png'),fullPage:true});
    await page.getByRole('link',{name:'Electronice',exact:true}).click();
    await expect(page.getByRole('heading',{level:1})).toHaveText('Electronice');
    await page.getByRole('link',{name:'Calculatoare',exact:true}).click();
    await expect(page).toHaveURL(/\/ro\/categories\/calculatoare$/);
    await page.getByRole('link',{name:'EN',exact:true}).click();
    await expect(page).toHaveURL(/\/en\/categories\/calculatoare$/);
    await expect(page.getByRole('heading',{level:1})).toHaveText('Computers');
    expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([]);
    await page.goto('/ro/categories');
    expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({path:testInfo.outputPath('catalog.png'),fullPage:true});
});

test('administrator creates category, child and typed field with real authorization', async ({page,browser,baseURL},testInfo) => {
    test.setTimeout(90000);
    const fixture=JSON.parse(readFileSync('.tools/catalog-browser.json','utf8'))[testInfo.project.name];
    await page.goto('/ro/login');
    await page.getByLabel('Adresa de email',{exact:true}).fill(fixture.email);
    await page.getByLabel('Parolă',{exact:true}).fill(fixture.password);
    await page.getByRole('button',{name:'Intră în cont',exact:true}).click();
    await page.goto('/ro/admin/categories');
    await page.getByRole('link',{name:'Adaugă o categorie',exact:false}).click();
    await page.getByLabel('Denumire în română',{exact:true}).fill('Categorie QA '+testInfo.project.name);
    await page.getByLabel('Denumire în engleză',{exact:true}).fill('QA category '+testInfo.project.name);
    await page.getByLabel('Adresă scurtă',{exact:true}).fill(fixture.slug);
    await page.getByLabel('Parolă',{exact:true}).fill(fixture.password);
    await page.getByRole('button',{name:'Salvează modificările',exact:true}).click();
    await expect(page.getByRole('status')).toContainText('Modificările au fost salvate.');
    const editURL=page.url();
    await page.getByRole('link',{name:'Adaugă un câmp',exact:false}).click();
    await page.getByLabel('Identificator stabil',{exact:true}).fill('size');
    await page.getByLabel('Etichetă în română',{exact:true}).fill('Mărime');
    await page.getByLabel('Etichetă în engleză',{exact:true}).fill('Size');
    await page.getByLabel('Tipul câmpului',{exact:true}).selectOption('select');
    await page.getByLabel('Opțiuni',{exact:true}).fill('small|Mic|Small\nlarge|Mare|Large');
    await page.getByLabel('Parolă',{exact:true}).fill(fixture.password);
    await page.getByRole('button',{name:'Salvează modificările',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Mărime',exact:true})).toBeVisible();
    expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([]);
    await page.screenshot({path:testInfo.outputPath('admin-category.png'),fullPage:true});
    const id=new URL(editURL).pathname.match(/categories\/(\d+)\/edit/)[1];
    await page.goto('/ro/admin/categories/create?parent_id='+id);
    await page.getByLabel('Denumire în română',{exact:true}).fill('Subcategorie QA');
    await page.getByLabel('Denumire în engleză',{exact:true}).fill('QA subcategory');
    await page.getByLabel('Adresă scurtă',{exact:true}).fill(fixture.slug+'-child');
    await page.getByLabel('Parolă',{exact:true}).fill(fixture.password);
    await page.getByRole('button',{name:'Salvează modificările',exact:true}).click();
    await expect(page.getByRole('status')).toContainText('Modificările au fost salvate.');
    const guest=await browser.newContext({baseURL});
    const publicPage=await guest.newPage();
    await publicPage.goto('/ro/categories/'+fixture.slug);
    await expect(publicPage.getByRole('link',{name:'Subcategorie QA',exact:true})).toBeVisible();
    await page.goto(editURL);
    await page.getByLabel('Vizibilă',{exact:true}).uncheck();
    await page.getByLabel('Parolă',{exact:true}).fill(fixture.password);
    await page.getByRole('button',{name:'Salvează modificările',exact:true}).click();
    await expect(page.getByRole('status')).toContainText('Modificările au fost salvate.');
    expect((await publicPage.goto('/ro/categories/'+fixture.slug+'-child')).status()).toBe(404);
    await publicPage.goto('/ro/admin/categories');
    await expect(publicPage).toHaveURL(/\/ro\/login$/);
    await guest.close();
});
