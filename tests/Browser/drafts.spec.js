import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { readFileSync } from 'node:fs';

test.describe.configure({ retries: 0 });
const tags = ['wcag2a','wcag2aa','wcag21aa','wcag22aa'];

test('real resumable draft, autosave, full wizard, protected preview and conflict recovery', async ({page,browser,baseURL},testInfo) => {
    test.setTimeout(150000);
    const fixture = JSON.parse(readFileSync('.tools/listing-browser.json','utf8'))[testInfo.project.name];
    const pageErrors = [];
    page.on('pageerror',error=>pageErrors.push(error.message));
    await page.goto('/ro/login');
    await page.getByLabel('Adresa de email',{exact:true}).fill(fixture.email);
    await page.getByLabel('Parolă',{exact:true}).fill(fixture.password);
    await page.getByRole('button',{name:'Intră în cont',exact:true}).click();
    await page.goto('/ro/sell');
    await page.screenshot({path:testInfo.outputPath('choose-category.png'),fullPage:true});
    await page.locator('.sell-category').filter({hasText:'Electronice'}).click();
    await page.locator('.sell-category').filter({hasText:'Calculatoare'}).click();
    await page.getByRole('button',{name:'Folosește această categorie'}).click();
    await expect(page).toHaveURL(/edit\/photos$/);
    await page.getByRole('button',{name:'Salvează și continuă'}).click();
    await expect(page).toHaveURL(/edit\/details$/);
    const detailsURL=page.url();
    const root=detailsURL.replace('/edit/details','');
    const status=page.locator('[data-save-status]');
    await page.getByLabel('Titlul anunțului',{exact:true}).fill('Laptop');
    await expect(status).toHaveText('Ciorna este salvată.');
    await page.reload();
    await expect(page.getByLabel('Titlul anunțului',{exact:true})).toHaveValue('Laptop');
    await page.getByLabel('Titlul anunțului',{exact:true}).fill('Laptop personal pentru lucru '+testInfo.project.name);
    await page.getByLabel('Descriere',{exact:true}).fill('Calculator personal folosit pentru lucru și lectură. Include încărcătorul, este îngrijit și funcționează bine.');
    await expect(status).toHaveText('Ciorna este salvată.');
    await page.screenshot({path:testInfo.outputPath('wizard-description.png'),fullPage:true});
    expect((await new AxeBuilder({page}).withTags(tags).analyze()).violations).toEqual([]);
    const originalViewport=page.viewportSize();
    for (const width of [320,390,768,1440]) {
        await page.setViewportSize({width,height:900});
        expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth), 'Wizard fits '+width).toBe(true);
    }
    await page.setViewportSize(originalViewport);
    await page.getByRole('button',{name:'Salvează și continuă'}).click();
    await page.locator('[name="attributes[condition]"]').selectOption('used');
    await page.locator('[name="attributes[warranty]"]').selectOption('0');
    await page.locator('[name="attributes[storage]"]').fill('512');
    await page.getByRole('button',{name:'Salvează și continuă'}).click();
    await page.getByRole('radio',{name:'Negociabil',exact:true}).check();
    await page.getByLabel('Preț',{exact:true}).fill('1250,05');
    await page.screenshot({path:testInfo.outputPath('wizard-price.png'),fullPage:true});
    await page.getByRole('button',{name:'Salvează și continuă'}).click();
    await page.getByLabel('Județ',{exact:true}).selectOption({label:'Cluj'});
    await page.getByLabel('Localitate',{exact:true}).fill('Cluj-Napoca');
    await page.getByRole('button',{name:'Salvează și continuă'}).click();
    await page.getByRole('radio',{name:/^Email /}).check();
    await page.getByRole('button',{name:'Salvează și continuă'}).click();
    await expect(page).toHaveURL(/\/preview$/);
    await expect(page.getByRole('heading',{name:'Informațiile anunțului sunt pregătite.'})).toBeVisible();
    await expect(page.locator('.preview-price')).toContainText('1.250,05 RON');
    await expect(page.locator('.listing-preview')).toContainText('Cluj-Napoca');
    expect(await page.content()).not.toContain(fixture.email);
    expect((await new AxeBuilder({page}).withTags(tags).analyze()).violations).toEqual([]);
    await page.screenshot({path:testInfo.outputPath('private-preview.png'),fullPage:true});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const guest=await browser.newContext({baseURL});
    const guestPage=await guest.newPage();
    await guestPage.goto(root+'/preview');
    await expect(guestPage).toHaveURL(/\/ro\/login$/);
    await guest.close();

    await page.goto(detailsURL);
    const stale=await page.context().newPage();
    await stale.goto(detailsURL);
    await page.getByLabel('Titlul anunțului',{exact:true}).fill('Laptop actualizat în prima filă');
    await expect(status).toHaveText('Ciorna este salvată.');
    stale.on('dialog',dialog=>dialog.accept());
    await stale.getByLabel('Titlul anunțului',{exact:true}).fill('Modificare din fila veche');
    await expect(stale.locator('[data-save-status]')).toContainText('altă filă');
    await stale.getByRole('link',{name:'Deschide versiunea salvată'}).click();
    await expect(stale.getByLabel('Titlul anunțului',{exact:true})).toHaveValue('Laptop actualizat în prima filă');
    await stale.close();

    await page.context().setOffline(true);
    await page.getByLabel('Titlul anunțului',{exact:true}).fill('Laptop recuperat după deconectare');
    await expect(status).toContainText('Salvarea nu a reușit');
    await page.context().setOffline(false);
    await page.getByRole('button',{name:'Reîncearcă salvarea'}).click();
    await expect(status).toHaveText('Ciorna este salvată.');
    await page.getByRole('button',{name:'Salvează și închide'}).click();
    await expect(page).toHaveURL(/\/account\/drafts$/);
    await expect(page.getByRole('heading',{name:'Laptop recuperat după deconectare'})).toBeVisible();
    await page.screenshot({path:testInfo.outputPath('drafts-dashboard.png'),fullPage:true});
    await page.locator('.draft-card').filter({hasText:'Laptop recuperat după deconectare'}).getByRole('link',{name:'Continuă editarea'}).click();
    await expect(page.getByLabel('Titlul anunțului',{exact:true})).toHaveValue('Laptop recuperat după deconectare');
    await page.getByRole('link',{name:'EN',exact:true}).click();
    await expect(page).toHaveURL(/\/en\/account\/drafts\/[^/]+\/edit\/details$/);
    await expect(page.getByRole('heading',{level:1})).toHaveText("Tell your item's story.");

    const noJS=await browser.newContext({baseURL,javaScriptEnabled:false,storageState:await page.context().storageState()});
    const plain=await noJS.newPage();
    await plain.goto(detailsURL);
    await plain.getByLabel('Titlul anunțului',{exact:true}).fill('Ciornă salvată fără JavaScript');
    await plain.getByRole('button',{name:'Salvează și închide'}).click();
    await expect(plain.getByRole('heading',{name:'Ciornă salvată fără JavaScript'})).toBeVisible();
    await noJS.close();
    expect(pageErrors).toEqual([]);
});
