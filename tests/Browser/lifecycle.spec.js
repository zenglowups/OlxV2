import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { readFileSync } from 'node:fs';

test.describe.configure({ retries: 0 });
test('publish real listing, public gallery and profile, reserve, edit, sell, repost and withdraw', async ({ page, browser, baseURL }, testInfo) => {
    test.setTimeout(180000);
    const fixture = JSON.parse(readFileSync('.tools/listing-browser.json','utf8'))[testInfo.project.name];
    const errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto('/ro/login');
    await page.getByLabel('Adresa de email',{exact:true}).fill(fixture.email);
    await page.getByLabel('Parolă',{exact:true}).fill(fixture.password);
    await page.getByRole('button',{name:'Intră în cont',exact:true}).click();
    await page.goto('/ro/sell?category=calculatoare');
    await page.getByRole('button',{name:'Folosește această categorie'}).click();
    const root=page.url().replace('/edit/photos','');
    const id=root.split('/').at(-1);
    await page.getByLabel('Alege fotografiile').setInputFiles('public/images/aproape-home.webp');
    await page.getByRole('button',{name:'Adaugă fotografiile',exact:true}).click();
    await expect(page.locator('.photo-item[data-photo-state="ready"]')).toHaveCount(1,{timeout:45000});
    const photoId=await page.locator('.photo-item').getAttribute('data-photo-id');
    await page.getByRole('button',{name:'Salvează și continuă'}).click();
    const title='QA Laptop pentru lucru '+testInfo.project.name;
    await page.getByLabel('Titlul anunțului',{exact:true}).fill(title);
    await page.getByLabel('Descriere',{exact:true}).fill('Anunț izolat pentru verificarea locală a platformei. Calculator personal îngrijit, cu încărcător inclus.');
    await page.getByRole('button',{name:'Salvează și continuă'}).click();
    await page.locator('[name="attributes[condition]"]').selectOption('used');
    await page.locator('[name="attributes[warranty]"]').selectOption('0');
    await page.getByRole('button',{name:'Salvează și continuă'}).click();
    await page.getByLabel('Preț',{exact:true}).fill('2400');
    await page.getByRole('button',{name:'Salvează și continuă'}).click();
    await page.getByLabel('Județ',{exact:true}).selectOption({label:'Cluj'});
    await page.getByLabel('Localitate',{exact:true}).fill('Cluj-Napoca');
    await page.getByRole('button',{name:'Salvează și continuă'}).click();
    await page.getByRole('radio',{name:/^Email /}).check();
    await page.getByRole('button',{name:'Salvează și continuă'}).click();
    await page.getByRole('button',{name:'Publică anunțul',exact:true}).click();
    await expect(page).toHaveURL(new RegExp('/ro/listings/'+id+'$'));
    const guest=await browser.newContext({baseURL,viewport:page.viewportSize()});
    const publicPage=await guest.newPage();
    await publicPage.goto('/ro/listings/'+id);
    await expect(publicPage.getByRole('heading',{level:1})).toHaveText(title);
    expect(await publicPage.content()).not.toContain(fixture.email);
    expect((await guest.request.get('/media/listings/'+photoId+'/card')).status()).toBe(200);
    await publicPage.getByRole('link',{name:'Vezi profilul',exact:true}).click();
    await expect(publicPage.locator('.market-card h3')).toContainText(title);
    await publicPage.goto('/ro/categories/electronice');
    await expect(publicPage.locator('.market-card').filter({hasText:title})).toBeVisible();
    await publicPage.goto('/ro/listings/'+id);
    await expect.poll(()=>publicPage.locator('.gallery-main img').evaluate(image=>image.naturalWidth)).toBeGreaterThan(0);
    await publicPage.screenshot({path:testInfo.outputPath('public-listing.png'),fullPage:true});
    expect((await new AxeBuilder({page:publicPage}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([]);
    for(const width of [320,390,768,1440]) {
        await publicPage.setViewportSize({width,height:900});
        expect(await publicPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Public listing fits '+width).toBe(true);
    }
    await publicPage.setViewportSize(page.viewportSize());
    await publicPage.getByRole('link',{name:'EN',exact:true}).click();
    await expect(publicPage).toHaveURL(new RegExp('/en/listings/'+id+'$'));

    const row=()=>page.locator('.manage-listing[data-listing-id="'+id+'"]');
    const action=async (label)=>{
        await page.goto('/ro/account/listings');
        await row().locator('summary').click();
        await row().getByRole('link',{name:label,exact:true}).click();
        await expect(page.getByRole('heading',{level:1})).toHaveText(label);
        await page.getByRole('button',{name:label,exact:true}).click();
    };
    await page.goto('/ro/account/listings');
    await expect(row().locator('.listing-state')).toHaveText('Activ');
    await row().locator('.manage-photo img').scrollIntoViewIfNeeded();
    await expect.poll(() => row().locator('.manage-photo img').evaluate(image => image.naturalWidth)).toBeGreaterThan(0);
    await page.screenshot({path:testInfo.outputPath('my-listings.png'),fullPage:true});
    expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([]);
    const viewport=page.viewportSize();
    for(const width of [320,390,768,1440]) {
        await page.setViewportSize({width,height:900});
        expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Listing management fits '+width).toBe(true);
    }
    await page.setViewportSize(viewport);
    await action('Marchează rezervat');
    await expect(row().locator('.listing-state')).toHaveText('Rezervat');
    await publicPage.goto('/ro/listings/'+id);
    await expect(publicPage.locator('.reserved-notice')).toBeVisible();
    await action('Disponibil din nou');
    await action('Editează anunțul');
    expect((await guest.request.get('/ro/listings/'+id)).status()).toBe(404);
    expect((await guest.request.get('/media/listings/'+photoId+'/card')).status()).toBe(404);
    await page.getByLabel('Titlul anunțului',{exact:true}).fill(title+' actualizat');
    await expect(page.locator('[data-save-status]')).toHaveText('Ciorna este salvată.');
    await page.goto(root+'/preview');
    await page.getByRole('button',{name:'Republică anunțul',exact:true}).click();
    await expect(page).toHaveURL(new RegExp('/ro/listings/'+id+'$'));
    await action('Marchează vândut');
    expect((await guest.request.get('/ro/listings/'+id)).status()).toBe(404);
    await expect(row().locator('.listing-state')).toHaveText('Vândut');
    await action('Repostează anunțul');
    expect((await guest.request.get('/ro/listings/'+id)).status()).toBe(200);
    await action('Retrage anunțul');
    await expect(row().locator('.listing-state')).toHaveText('Retras');
    expect((await guest.request.get('/ro/listings/'+id)).status()).toBe(404);
    expect((await guest.request.get('/media/listings/'+photoId+'/card')).status()).toBe(404);
    await expect(row().locator('summary')).toHaveCount(0);
    await guest.close();
    expect(errors).toEqual([]);
});
